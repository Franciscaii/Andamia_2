type Regla = [RegExp, (...grupos: string[]) => string];

const traducir = (t: string) => EN[t] ?? t;

/** Textos con partes que cambian (nombres, números, fechas): se arman con estas reglas. */
export const REGLAS: Regla[] = [
  [/^(Completar|Marcar como pendiente): (.+)$/, (a, b) => `${traducir(a + ":")} ${b}`],
  [/^(Mover|Editar|Borrar|Abrir|Quitar|Renombrar|Marcar|Completar|Añadir tarea en|Nueva tarea en|Ajustes de|Vista previa de|Tema de|Racha actual|Historial de|Nombre de|Detalle de|Icono) (.+)$/, (a, b) => `${traducir(a)} ${aIngles(b)}`],
  [/^(\d+) tareas? hechas?\.? ?(.*)$/, (n, r) => `${n} task${n === "1" ? "" : "s"} done. ${traducir(r)}`.trim()],
  [/^(\d+) de (\d+) completadas?$/, (a, b) => `${a} of ${b} completed`],
  [/^(\d+) (minutos?|horas?|días?|semanas?|meses|años?) antes$/, (n, u) => `${n} ${{ minuto: "minute", minutos: "minutes", hora: "hour", horas: "hours", día: "day", días: "days", semana: "week", semanas: "weeks", meses: "months", año: "year", años: "years" }[u] ?? u}${Number(n) === 1 ? "" : ""} before`],
  [/^Cada (\d+) (días|semanas|meses|años)$/, (n, u) => `Every ${n} ${{ días: "days", semanas: "weeks", meses: "months", años: "years" }[u]}`],
  [/^(\d+) veces? por semana$/, (n) => `${n} time${n === "1" ? "" : "s"} per week`],
  [/^(\d+) días?$/, (n) => `${n} day${n === "1" ? "" : "s"}`],
  [/^(\d+) (veces|vez)$/, (n) => `${n} time${n === "1" ? "" : "s"}`],
];

/** "9 de noviembre" ya sale con los meses en inglés: se reordena a "November 9". */
const MESES_EN = "January|February|March|April|May|June|July|August|September|October|November|December|Jan|Feb|Mar|Apr|Jun|Jul|Aug|Sep|Oct|Nov|Dec";
const FECHA_CON_DE = new RegExp(`(\\d{1,2}) de (${MESES_EN})\\b`, "g");

export function aIngles(texto: string): string {
  const exacto = EN[texto];
  if (exacto !== undefined) return exacto;
  const t = texto.trim();
  if (!t) return texto;
  const lado = EN[t];
  if (lado !== undefined) return texto.replace(t, lado);
  for (const [re, f] of REGLAS) {
    const m = t.match(re);
    if (m) return texto.replace(t, f(...m.slice(1)));
  }
  if (FECHA_CON_DE.test(t)) {
    FECHA_CON_DE.lastIndex = 0;
    return texto.replace(FECHA_CON_DE, "$2 $1");
  }
  return texto;
}
